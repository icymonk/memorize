import { expect, test } from '@playwright/test'
import { signUp } from './helpers'

/** E2E 흐름 4: 노트 작성 → 새로고침 후 유지 → 편집 잠금 중 다른 멤버는 읽기만 하고 고친 내용은 바로 보임 (블록 끌어 옮기기는 수동 확인) */
test('a note survives reload and is read-only for another member while locked', async ({ browser }) => {
  test.setTimeout(180_000)
  const pa = await (await browser.newContext()).newPage()
  const personal = await signUp(pa, 'hana')
  await pa.getByRole('button', { name: /내 공간/ }).first().click()
  await pa.getByRole('menuitem', { name: '워크스페이스 만들기' }).click()
  await pa.locator('#ws-name').fill('노트 스터디')
  await pa.locator('button[form="create-workspace"]').click()
  await pa.waitForURL(url => !url.pathname.startsWith(`/s/${personal}`) && /\/s\/[^/]+/.test(url.pathname))
  const ws = pa.url().match(/\/s\/([^/?#]+)/)![1]!

  await pa.goto(`/s/${ws}/members`)
  await pa.getByRole('tab', { name: '초대' }).click()
  await pa.getByRole('button', { name: '초대 만들기' }).click()
  const code = (await pa.locator('span.font-mono').first().textContent())!.trim()

  const pb = await (await browser.newContext()).newPage()
  await signUp(pb, 'dori')
  await pb.getByRole('button', { name: /내 공간/ }).first().click()
  await pb.getByRole('menuitem', { name: '코드로 참여' }).click()
  await pb.getByRole('dialog').locator('input').first().fill(code)
  await pb.locator('button[form="join-with-code"]').click()
  await pb.waitForURL(/\/invite\//)
  await pb.getByRole('button', { name: '참여하기' }).click()
  await pb.waitForURL(new RegExp(`/s/${ws}`))

  await pa.goto(`/s/${ws}/notes`)
  await pa.getByRole('button', { name: '새 페이지' }).click()
  await pa.waitForURL(/\/notes\/[^/]+$/)
  await pa.getByPlaceholder('제목 없음').fill('E2E 노트')
  await pa.locator('.ProseMirror').click()
  await pa.keyboard.type('첫 문단')
  await pa.keyboard.press('Enter')
  await pa.keyboard.type('둘째 문단')
  await expect(pa.getByText('저장됨')).toBeVisible()
  await pa.reload()
  await expect(pa.locator('.ProseMirror')).toContainText('둘째 문단')
  await expect(pa.getByPlaceholder('제목 없음')).toHaveValue('E2E 노트')

  await pb.goto(pa.url())
  await expect(pb.getByText('hana님이 편집 중이에요')).toBeVisible()
  await expect(pb.locator('.ProseMirror')).toContainText('둘째 문단')
  await expect(pb.locator('.ProseMirror')).toHaveAttribute('contenteditable', 'false')

  // 다른 사람이 고친 내용이 새로고침 없이 보인다
  await pa.locator('.ProseMirror').click()
  await pa.keyboard.press('Control+End')
  await pa.keyboard.press('Enter')
  await pa.keyboard.type('셋째 문단')
  await expect(pa.getByText('저장됨')).toBeVisible()
  await expect(pb.locator('.ProseMirror')).toContainText('셋째 문단')

  // NOTE-62 블록 댓글: 읽기 전용인 멤버도 문장을 골라 댓글을 단다
  await pb.locator('.ProseMirror p', { hasText: '둘째 문단' }).click({ clickCount: 3 })
  await pb.getByRole('button', { name: '댓글 달기' }).click()
  await pb.locator('#page-comment-draft').fill('여기 좋아요')
  await pb.getByRole('button', { name: '남기기' }).click()
  await expect(pa.getByTestId('comment-quote')).toContainText('둘째 문단')
  await expect(pa.getByText('여기 좋아요')).toBeVisible()

  // 작성자가 피드백을 요청하면, 요청받은 멤버가 스탬프와 총평을 남긴다 (CMN-23·24)
  await pa.getByRole('button', { name: '피드백 요청' }).click()
  await pa.getByLabel('dori').check()
  await pa.getByRole('button', { name: '저장', exact: true }).click()
  await expect(pa.getByText('dori님에게 요청함')).toBeVisible()
  await pb.reload()
  await pb.getByRole('button', { name: '피드백 남기기' }).click()
  await pb.getByRole('radio', { name: '👍 잘했어요' }).click()
  await pb.getByLabel('총평 (선택)').fill('구성이 좋아요')
  await pb.getByRole('button', { name: '남기기', exact: true }).first().click()
  await expect(pa.getByText('구성이 좋아요')).toBeVisible()
  await expect(pa.locator('section[aria-label="피드백"]')).toContainText('👍 잘했어요')

  // 2-E2: 열린 제출형 미션에 다른 멤버가 참여해 제출
  await pa.goto(`/s/${ws}/missions`)
  await pa.getByRole('button', { name: '미션 만들기' }).click()
  await pa.locator('#mis-title').fill('독후감 내기')
  await pa.getByRole('radio', { name: /제출형/ }).click()
  await pa.getByRole('radio', { name: '직접 고르기' }).click()
  await pa.getByLabel('열린 미션').check()
  await pa.locator('button[form="mission-form"]').click()
  await pa.waitForURL(/\/missions\/[^/]+$/)
  await pb.goto(pa.url())
  await pb.getByRole('button', { name: '참여하기' }).click()
  await pb.getByRole('button', { name: '제출', exact: true }).click()
  await pb.getByLabel('제출 내용').fill('재밌게 읽었어요')
  await pb.locator('form').getByRole('button', { name: '제출', exact: true }).click()
  await expect(pb.getByText('검토 대기')).toBeVisible()
  await expect(pb.getByText('재밌게 읽었어요')).toBeVisible()
  // 2-E3: 진행자가 현황판에서 승인
  await pa.reload()
  await expect(pa.locator('section[aria-label="현황판"]')).toContainText('검토 대기')
  await pa.getByRole('button', { name: '승인', exact: true }).click()
  await expect(pa.getByRole('button', { name: '승인', exact: true })).toHaveCount(0)
  await pb.reload()
  await expect(pb.getByText('승인', { exact: true })).toBeVisible()

  // NOTE-24 `[[`로 페이지 링크 → 링크된 페이지 아래 "이 페이지를 언급한 페이지"
  const first = pa.url()
  await pa.goto(`/s/${ws}/notes`)
  await pa.getByRole('button', { name: '새 페이지' }).click()
  await pa.waitForURL(u => /\/notes\/[^/]+$/.test(u.pathname) && u.href !== first)
  await pa.getByPlaceholder('제목 없음').fill('링크 노트')
  await pa.locator('.ProseMirror').click()
  await pa.keyboard.type('[[')
  await pa.getByRole('dialog').getByText('E2E 노트').click()
  const linked = (await pa.locator('.ProseMirror a').first().getAttribute('href'))!.split('/').pop()!
  await expect(pa.locator('.ProseMirror').getByText('E2E 노트')).toBeVisible()
  await expect(pa.getByText('저장됨')).toBeVisible()
  await pa.reload()
  await expect(pa.locator('.ProseMirror').getByText('E2E 노트')).toBeVisible({ timeout: 10_000 })
  await pa.locator('.ProseMirror').getByText('E2E 노트').click()
  await pa.waitForURL(u => u.pathname.endsWith(`/notes/${linked}`))
  await expect(pa.getByTestId('related-notes')).toContainText('링크 노트', { timeout: 15_000 })

  // NOTE-06 구조 블록: `/표`로 표를 넣고 칸을 채운 뒤 행을 늘린다
  await pa.locator('.ProseMirror').click()
  await pa.keyboard.press('Control+End')
  await pa.keyboard.press('Enter')
  await pa.keyboard.type('/표')
  await pa.keyboard.press('Enter')
  await pa.getByLabel('칸 1-1').fill('단어')
  await pa.getByLabel('칸 1-1').press('Tab')
  await pa.getByRole('button', { name: '행 추가' }).click()
  await expect(pa.getByTestId('simple-table').locator('tr')).toHaveCount(3)
  await expect(pa.getByText('저장됨')).toBeVisible()
  await pa.reload()
  await expect(pa.getByLabel('칸 1-1')).toHaveValue('단어', { timeout: 10_000 })
  await expect(pa.getByTestId('simple-table').locator('tr')).toHaveCount(3)

  // NOTE-11 그리기 블록: 두 획을 긋고 하나를 지우개로 지운다 (끝은 표라 첫 문단 뒤에 넣는다)
  await pa.locator('.ProseMirror').focus()
  await pa.keyboard.press('Control+Home')
  await pa.keyboard.press('End')
  await pa.keyboard.press('Enter')
  await pa.keyboard.type('/그리기')
  await pa.keyboard.press('Enter')
  const canvas = pa.getByTestId('drawing-block').locator('svg')
  const box = (await canvas.boundingBox())!
  const stroke = async (y: number) => {
    await pa.mouse.move(box.x + box.width * 0.2, box.y + box.height * y)
    await pa.mouse.down()
    await pa.mouse.move(box.x + box.width * 0.5, box.y + box.height * y, { steps: 5 })
    await pa.mouse.move(box.x + box.width * 0.8, box.y + box.height * y, { steps: 5 })
    await pa.mouse.up()
  }
  await stroke(0.3)
  await stroke(0.7)
  await expect(canvas.locator('[data-stroke]')).toHaveCount(2)
  await pa.getByRole('button', { name: '지우개' }).click()
  await pa.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.7)
  await expect(canvas.locator('[data-stroke]')).toHaveCount(1)
  await expect(pa.getByText('저장됨')).toBeVisible()
  await pa.reload()
  await expect(pa.getByTestId('drawing-block').locator('[data-stroke]')).toHaveCount(1, { timeout: 10_000 })

  // NOTE-63 버전 기록: 다른 페이지로 나가면 잠금이 풀리며 버전이 남는다. 칸을 바꾼 뒤 그 버전으로 되돌린다
  const noteUrl = pa.url()
  await pa.getByTestId('related-notes').getByText('링크 노트').click()
  await pa.waitForURL(u => u.href !== noteUrl)
  await pa.goto(noteUrl)
  await pa.getByLabel('칸 1-1').fill('바뀜')
  await pa.getByLabel('칸 1-1').press('Tab')
  await expect(pa.getByText('저장됨')).toBeVisible()
  await pa.getByRole('button', { name: '버전 기록' }).click()
  await pa.getByTestId('version-item').first().click()
  await expect(pa.getByTestId('version-preview')).toContainText('단어', { timeout: 10_000 })
  await pa.getByRole('button', { name: '이 버전으로 되돌리기' }).click()
  await pa.getByRole('dialog').getByRole('button', { name: '되돌리기', exact: true }).click()
  await expect(pa.getByLabel('칸 1-1')).toHaveValue('단어', { timeout: 15_000 })
})
